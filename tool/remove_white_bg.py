"""Remove white background from icon_official.png using splash_logo.png as mask.

splash_logo.png already has the correct transparent background (generated by
the Dart tool). We use its alpha channel as the definitive mask for which
pixels should be transparent in icon_official.png.
"""
from pathlib import Path
from PIL import Image

OFFICIAL = Path('assets/branding/icon_official.png')
SPLASH = Path('assets/branding/splash_logo.png')


def main():
    # First regenerate splash_logo from the original icon_official
    # by restoring the original and running edge flood-fill
    import subprocess
    print('Restoring original icon_official.png...')
    subprocess.run(['git', 'checkout', '109cba8', '--', str(OFFICIAL)], check=True)

    # Now read both images
    official = Image.open(OFFICIAL).convert('RGBA')
    splash = Image.open(SPLASH).convert('RGBA')

    print(f'Official: {official.size}')
    print(f'Splash:   {splash.size}')

    # The splash is scaled to 88% of the canvas. We need to create a full-size
    # alpha mask from it. The splash has the logo at 88% centered on the canvas.
    # Pixels outside the logo area in the splash are already transparent.

    # Create a full-size alpha mask:
    # - Where splash alpha == 0 → make official transparent
    # - Where splash alpha > 0 → keep official as-is
    ow, oh = official.size
    sw, sh = splash.size

    # Scale splash back to official size to get the alpha mask
    splash_resized = splash.resize((ow, oh), Image.LANCZOS)
    splash_alpha = splash_resized.split()[3]  # Alpha channel

    official_pixels = official.load()
    mask_pixels = splash_alpha.load()

    # Pixels that are transparent in splash but opaque in official → make transparent
    changed = 0
    for y in range(oh):
        for x in range(ow):
            if mask_pixels[x, y] == 0:
                r, g, b, a = official_pixels[x, y]
                if a > 0:
                    official_pixels[x, y] = (0, 0, 0, 0)
                    changed += 1

    print(f'Made {changed} pixels transparent using splash mask')

    # But this only handles the splash area (88%). The remaining 12% border
    # should also be transparent. Let's do an edge flood-fill on the result.
    print('Running edge flood-fill on remaining border...')
    w, h = official.size

    KEY_MIN_CHANNEL = 200
    KEY_MAX_SATURATION = 30

    def is_light(r, g, b):
        mx = max(r, g, b)
        mn = min(r, g, b)
        return mx >= KEY_MIN_CHANNEL and (mx - mn) <= KEY_MAX_SATURATION

    visited = [[False] * w for _ in range(h)]
    stack = []
    for x in range(w):
        stack.append((x, 0))
        stack.append((x, h - 1))
    for y in range(1, h - 1):
        stack.append((0, y))
        stack.append((w - 1, y))

    flood_removed = 0
    while stack:
        x, y = stack.pop()
        if visited[y][x]:
            continue
        r, g, b, a = official_pixels[x, y]
        if a == 0 or not is_light(r, g, b):
            visited[y][x] = True
            continue
        visited[y][x] = True
        official_pixels[x, y] = (0, 0, 0, 0)
        flood_removed += 1
        if x > 0: stack.append((x - 1, y))
        if x < w - 1: stack.append((x + 1, y))
        if y > 0: stack.append((x, y - 1))
        if y < h - 1: stack.append((x, y + 1))

    print(f'Edge flood-fill removed {flood_removed} more pixels')

    # Final stats
    total = w * h
    alpha = official.getchannel('A')
    transparent = sum(1 for p in alpha.tobytes() if p == 0)
    print(f'Result: {transparent}/{total} transparent ({transparent/total*100:.1f}%)')

    official.save(OFFICIAL, 'PNG')
    print(f'Saved: {OFFICIAL} ({OFFICIAL.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
